def get_lang():
    code = request.cookies.get("lang", DEFAULT_LANG)
    return code if code in LANGS else DEFAULT_LANG


def _(text, **kw):
    lang = get_lang()
    if lang != DEFAULT_LANG and text in TR:
        text = TR[text][_IDX[lang]]
    return text.format(**kw) if kw else text


def fmt_date(d, pattern):
    """strftime that uses localized weekday/month names for %A, %B and %b."""
    lang = get_lang()
    if lang != DEFAULT_LANG:
        pattern = (pattern.replace("%A", WEEKDAYS[lang][d.weekday()])
                   .replace("%B", MONTHS[lang][d.month - 1])
                   .replace("%b", MONTHS_SHORT[lang][d.month - 1]))
    return d.strftime(pattern)
